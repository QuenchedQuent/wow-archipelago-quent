--[[
  Archipelago integration for AzerothCore + Eluna.

  - Detects checks (quest completion, level, exploration, rare kills, trainer purchases) and writes them
    to ap_location_outbox for the Python bridge.
  - Grants items the bridge puts in ap_item_inbox (spells, zone keys, items, money).
  - Fences zones the player has no key for.
  - Feeds the Archipelago addon over addon messages (prefix "AP").

  ID ENCODING must match apworld/wow/data.py:
    location = LOC_BASE  + kind * KIND_SIZE + game_id
    item     = ITEM_BASE + kind * KIND_SIZE + payload

  Hook numbers are from Eluna's Hooks.h; verify them against the Eluna/ALE build on
  your server (`grep PLAYER_EVENT_ON_ Hooks.h`).
]]

local AP = {}

AP.LOC_BASE  = 870000000
AP.ITEM_BASE = 880000000
AP.KIND_SIZE = 1000000
AP.LOC  = { QUEST = 0, EXPLORE = 1, LEVEL = 2, RARE = 3, VENDOR = 4, TRAINER = 5, GOAL = 9 }
AP.ITEM = { SPELL = 0, ZONE = 1, GAME_ITEM = 2, MONEY = 3, FLIGHT = 4 }

AP.PREFIX       = "AP"
AP.TICK_MS      = 1000
AP.SWEEP_TICKS  = 5      -- quest sweep / tracker refresh every N ticks
AP.MAX_LEVEL_CHECK = 60

-- Zone fence and locked spells come from archipelago_data.lua (generated by
-- tools/extract_data.py). It is read lazily, so script load order doesn't matter.
-- Fallback fence if the data file is missing.
AP.FALLBACK_ZONE_LOCKS = {
    [12] = { name = "Elwynn Forest", key = 12, key_name = "Zone: Elwynn Forest",
             free_areas = { [9] = true, [23] = true, [24] = true, [34] = true, [59] = true } },
    [1519] = { name = "Stormwind City", key = 12, key_name = "Zone: Elwynn Forest" },
    [40] = { name = "Westfall", key = 40, key_name = "Zone: Westfall" },
}
AP.FALLBACK_FENCE_MAP = 0

local function zoneLocks()
    return (ArchipelagoData and ArchipelagoData.zone_locks) or AP.FALLBACK_ZONE_LOCKS
end

-- Per class (player:GetClass()): spells that are Archipelago items, and trainer checks.
local function lockedSpells(player)
    local t = ArchipelagoData and ArchipelagoData.locked_spells
    return (t and t[player:GetClass()]) or {}
end

local function trainerChecks(player)
    local t = ArchipelagoData and ArchipelagoData.trainer_checks
    return (t and t[player:GetClass()]) or {}
end
local function fenceMap()
    return (ArchipelagoData and ArchipelagoData.fence_map) or AP.FALLBACK_FENCE_MAP
end

-- Where fenced players go if there is no last allowed position yet (Northshire Abbey).
AP.RETURN_POINT = { map = 0, x = -8949.95, y = -132.49, z = 83.53, o = 0.0 }

-- Eluna hook ids
local PLAYER_EVENT_ON_CHARACTER_CREATE = 1
local PLAYER_EVENT_ON_CHARACTER_DELETE = 2
local PLAYER_EVENT_ON_LOGIN          = 3
local PLAYER_EVENT_ON_LOGOUT         = 4
local PLAYER_EVENT_ON_KILL_CREATURE  = 7
local PLAYER_EVENT_ON_LEVEL_CHANGE   = 13
local PLAYER_EVENT_ON_UPDATE_ZONE    = 27
local PLAYER_EVENT_ON_COMMAND        = 42
local PLAYER_EVENT_ON_LEARN_SPELL    = 44
local PLAYER_EVENT_ON_COMPLETE_QUEST = 54
local SERVER_EVENT_ON_ADDON_MESSAGE  = 30
local CHAT_MSG_WHISPER               = 7

-- Per-character runtime state, keyed by low guid.
local state = {}

---------------------------------------------------------------------------------------
-- helpers
---------------------------------------------------------------------------------------

local function locId(kind, gameId)
    return AP.LOC_BASE + kind * AP.KIND_SIZE + gameId
end

local function decode(id, base)
    local off = id - base
    return math.floor(off / AP.KIND_SIZE), off % AP.KIND_SIZE
end

local function say(player, text)
    player:SendBroadcastMessage("|cff00ccff[Archipelago]|r " .. text)
end

local function toAddon(player, ...)
    local msg = table.concat({ ... }, "\t")
    if #msg > 250 then msg = msg:sub(1, 250) end
    player:SendAddonMessage(AP.PREFIX, msg, CHAT_MSG_WHISPER, player)
end

local function getState(player)
    return state[player:GetGUIDLow()]
end

---------------------------------------------------------------------------------------
-- checks (game -> AP)
---------------------------------------------------------------------------------------

local function sendCheck(player, kind, gameId)
    local st = getState(player)
    if not st then return end
    local id = locId(kind, gameId)
    if st.sent[id] then return end
    st.sent[id] = true
    CharDBExecute(string.format(
        "INSERT IGNORE INTO ap_location_outbox (char_guid, location_id) VALUES (%d, %d)",
        st.guid, id))
end

local function checkLevels(player)
    local level = math.min(player:GetLevel(), AP.MAX_LEVEL_CHECK)
    for lvl = 2, level do
        sendCheck(player, AP.LOC.LEVEL, lvl)
    end
    local st = getState(player)
    if st and st.goalLevel > 0 and player:GetLevel() >= st.goalLevel then
        sendCheck(player, AP.LOC.GOAL, 0)
    end
end

-- Robust quest detection: any tracked quest that is rewarded counts, even if the
-- event hook was missed (server restart, reload, hook semantics).
-- Either/or quests (exclusive groups: only one can ever be done) are one location in a slot,
-- whichever member the APWorld picked. Completing any member checks it.
local function questGroup(questId)
    local t = ArchipelagoData and ArchipelagoData.quest_groups
    return (t and t[questId]) or { questId }
end

local function sendQuestCheck(player, st, questId)
    for _, member in ipairs(questGroup(questId)) do
        local id = locId(AP.LOC.QUEST, member)
        if member == questId or st.locations[id] then sendCheck(player, AP.LOC.QUEST, member) end
    end
end

local function sweepQuests(player, st)
    for id, _ in pairs(st.locations) do
        local kind, questId = decode(id, AP.LOC_BASE)
        if kind == AP.LOC.QUEST and not st.sent[id] then
            for _, member in ipairs(questGroup(questId)) do
                if player:GetQuestRewardStatus(member) then
                    sendCheck(player, AP.LOC.QUEST, questId)
                    break
                end
            end
        end
    end
end

---------------------------------------------------------------------------------------
-- items (AP -> game)
---------------------------------------------------------------------------------------

-- Apply an item's effect. Returns false if it must be retried later (e.g. bags full).
local function applyItem(player, st, itemId, announce)
    local kind, payload = decode(itemId, AP.ITEM_BASE)
    if kind == AP.ITEM.SPELL then
        st.spells[payload] = true   -- before LearnSpell: the learn hook must see it as allowed
        if not player:HasSpell(payload) then player:LearnSpell(payload) end
    elseif kind == AP.ITEM.ZONE then
        st.zones[payload] = true
    elseif kind == AP.ITEM.GAME_ITEM then
        if announce then
            local added = player:AddItem(payload, 1)
            if not added then
                if not st.bagWarned then say(player, "Bags full - item will be delivered later.") end
                st.bagWarned = true
                return false
            end
            st.bagWarned = false
        end
    elseif kind == AP.ITEM.MONEY then
        if announce then player:ModifyMoney(payload) end
    end
    return true
end

local function processInbox(player, st)
    local q = CharDBQuery(string.format(
        "SELECT ap_index, item_id, item_name, sender_name FROM ap_item_inbox "
            .. "WHERE char_guid = %d AND granted = 0 ORDER BY ap_index LIMIT 20", st.guid))
    if not q then return end
    repeat
        local index = q:GetUInt32(0)
        if not st.granting[index] then
            local itemId, name, sender = q:GetUInt32(1), q:GetString(2), q:GetString(3)
            if applyItem(player, st, itemId, true) then
                st.granting[index] = true
                CharDBExecute(string.format(
                    "UPDATE ap_item_inbox SET granted = 1 WHERE char_guid = %d AND ap_index = %d",
                    st.guid, index))
                say(player, string.format("Received |cffffff00%s|r from %s", name, sender))
                toAddon(player, "I", name, sender)
            else
                break -- keep order; retry next tick
            end
        end
    until not q:NextRow()
end

-- Re-apply persistent unlocks (zone keys, allowed spells) from already-granted items on login.
local function loadUnlocks(st)
    local q = CharDBQuery(string.format(
        "SELECT item_id FROM ap_item_inbox WHERE char_guid = %d AND granted = 1", st.guid))
    if not q then return end
    repeat
        local kind, payload = decode(q:GetUInt32(0), AP.ITEM_BASE)
        if kind == AP.ITEM.ZONE then st.zones[payload] = true end
        if kind == AP.ITEM.SPELL then st.spells[payload] = true end
    until not q:NextRow()
end

---------------------------------------------------------------------------------------
-- spell locks
---------------------------------------------------------------------------------------

-- Remove locked spells the player knows without having received them from Archipelago
-- (quest rewards, characters that existed before, anything that slipped past trainers).
local function stripLockedSpells(player, st, announce)
    for spellId in pairs(lockedSpells(player)) do
        if not st.spells[spellId] and player:HasSpell(spellId) then
            player:RemoveSpell(spellId)
            if announce then
                say(player, "That spell is an Archipelago item - it will arrive from the multiworld.")
            end
        end
    end
end

---------------------------------------------------------------------------------------
-- zone fence
---------------------------------------------------------------------------------------

-- nil if the player may be here, else the reason they may not.
local function fenceReason(player, st)
    if player:GetMapId() ~= fenceMap() then
        return "That's outside this randomizer's world."
    end
    local zone, area = player:GetZoneId(), player:GetAreaId()
    if zone == 0 then return nil end     -- no zone (open sea, map edges): leave it alone
    local lock = zoneLocks()[zone]
    if not lock then
        return "That zone is outside this randomizer's world."
    end
    if st.zones[lock.key or zone] or (lock.free_areas and lock.free_areas[area]) then
        return nil
    end
    return "You need |cffffff00" .. (lock.key_name or ("Zone: " .. lock.name)) .. "|r to go there."
end

-- Fenced players go back to where they last stood inside the fence, so walking into a
-- locked zone from Elwynn doesn't send you all the way back to Northshire.
AP.FENCE_COOLDOWN_TICKS = 3   -- let a fence teleport land before checking again

local function enforceZone(player, st)
    if player:IsGM() or st.ticks < (st.fenceUntil or 0) then return end
    local reason = fenceReason(player, st)
    if not reason then
        if not player:IsFalling() and not player:IsDead() then
            st.safe = { map = player:GetMapId(), x = player:GetX(), y = player:GetY(),
                        z = player:GetZ(), o = player:GetO() }
        end
        return
    end
    -- st.safe is always inside the fence: keys are never taken away, and relinking to a
    -- new seed rebuilds the state (and forgets st.safe).
    local p = st.safe or AP.RETURN_POINT
    st.fenceUntil = st.ticks + AP.FENCE_COOLDOWN_TICKS
    say(player, reason)
    player:Teleport(p.map, p.x, p.y, p.z, p.o)
end

---------------------------------------------------------------------------------------
-- tracker / status sync
---------------------------------------------------------------------------------------

-- L <id> <checked> <name> <flags> <contents>; contents last so the 250-char cap only clips it.
local function sendLocation(player, id, loc)
    toAddon(player, "L", id, loc.checked and 1 or 0, loc.name, loc.flags, loc.contents)
    -- T <spell> <level> <copper> <spell name>: what the trainer window needs for a trainer check.
    local kind, spell = decode(id, AP.LOC_BASE)
    if kind == AP.LOC.TRAINER then
        for _, c in ipairs(trainerChecks(player)) do
            if c.spell == spell then toAddon(player, "T", c.spell, c.level, c.cost, c.name) end
        end
    end
end

local function refreshFromDB(player, st, pushChanges)
    local q = CharDBQuery(string.format(
        "SELECT l.location_id, l.checked, l.name, COALESCE(c.contents, ''), COALESCE(c.flags, 0) "
            .. "FROM ap_locations l LEFT JOIN ap_location_contents c "
            .. "ON c.char_guid = l.char_guid AND c.location_id = l.location_id "
            .. "WHERE l.char_guid = %d", st.guid))
    if q then
        repeat
            local id, checked, name = q:GetUInt32(0), q:GetUInt32(1) == 1, q:GetString(2)
            local contents, flags = q:GetString(3), q:GetUInt32(4)
            local known = st.locations[id]
            if known == nil then
                known = { checked = checked, name = name, contents = contents, flags = flags }
                st.locations[id] = known
                if pushChanges then sendLocation(player, id, known) end
            elseif known.contents ~= contents then
                known.contents, known.flags, known.checked = contents, flags, checked or known.checked
                if pushChanges then sendLocation(player, id, known) end
            elseif checked and not known.checked then
                known.checked = true
                if pushChanges then toAddon(player, "C", id) end
            end
        until not q:NextRow()
    end

    local s = CharDBQuery(string.format(
        "SELECT connected, slot_name, checked_count, total_count, goal_level, seed_name FROM ap_state WHERE char_guid = %d",
        st.guid))
    local status
    if st.seed == nil then st.seed = s and s:GetString(5) or "" end   -- seed this state was built for
    if s then
        st.goalLevel = s:GetUInt32(4)
        status = table.concat({ s:GetUInt32(0), s:GetString(1), s:GetUInt32(2), s:GetUInt32(3), st.goalLevel }, "\t")
    else
        status = "0\t\t0\t0\t0"
    end
    if pushChanges and status ~= st.lastStatus then
        toAddon(player, "S", status)
    end
    st.lastStatus = status
end

local function fullSyncToAddon(player, st)
    toAddon(player, "RESET")
    toAddon(player, "S", st.lastStatus or "0\t\t0\t0\t0")
    for id, loc in pairs(st.locations) do
        sendLocation(player, id, loc)
    end
    toAddon(player, "END")
end

---------------------------------------------------------------------------------------
-- lifecycle
---------------------------------------------------------------------------------------

local function initPlayer(player)
    local guid = player:GetGUIDLow()
    local st = {
        guid = guid, sent = {}, granting = {}, zones = {}, spells = {}, locations = {},
        goalLevel = 0, ticks = 0, lastStatus = nil, stripPending = false,
    }
    state[guid] = st

    local q = CharDBQuery(string.format(
        "SELECT location_id FROM ap_location_outbox WHERE char_guid = %d", guid))
    if q then
        repeat st.sent[q:GetUInt32(0)] = true until not q:NextRow()
    end
    loadUnlocks(st)
    stripLockedSpells(player, st, false)
    refreshFromDB(player, st, false)
    checkLevels(player)
    sweepQuests(player, st)
end

-- The client relinked this character to another seed (and cleared its old rows):
-- start over so nothing from the old game (zones, spells, sent checks) carries over.
local function relinked(player, st)
    local s = CharDBQuery(string.format("SELECT seed_name FROM ap_state WHERE char_guid = %d", st.guid))
    return (s and s:GetString(0) or "") ~= st.seed
end

local function tickPlayer(player)
    local st = getState(player)
    if not st then
        initPlayer(player)
        st = getState(player)
    elseif st.ticks % AP.SWEEP_TICKS == AP.SWEEP_TICKS - 1 and relinked(player, st) then
        say(player, "Linked to a new Archipelago game.")
        initPlayer(player)
        st = getState(player)
        fullSyncToAddon(player, st)
    end
    st.ticks = st.ticks + 1
    processInbox(player, st)
    if st.stripPending then
        st.stripPending = false
        stripLockedSpells(player, st, true)
    end
    enforceZone(player, st)
    -- Subzone changes don't always fire ON_UPDATE_ZONE; poll the current area too.
    local area = player:GetAreaId()
    if next(st.locations) ~= nil and st.locations[locId(AP.LOC.EXPLORE, area)] then
        sendCheck(player, AP.LOC.EXPLORE, area)
    end
    if st.ticks % AP.SWEEP_TICKS == 0 then
        refreshFromDB(player, st, true)
        sweepQuests(player, st)
        checkLevels(player)
    end
end

CreateLuaEvent(function()
    for _, player in ipairs(GetPlayersInWorld() or {}) do
        local ok, err = pcall(tickPlayer, player)
        if not ok then print("[Archipelago] tick error: " .. tostring(err)) end
    end
end, AP.TICK_MS, 0)

-- AzerothCore hands a deleted character's guid to the next new character, so drop any
-- Archipelago rows stored under it.
local function forgetCharacter(guid)
    for _, t in ipairs({ "ap_item_inbox", "ap_location_outbox", "ap_locations", "ap_location_contents", "ap_state" }) do
        CharDBExecute(string.format("DELETE FROM %s WHERE char_guid = %d", t, guid))
    end
end

RegisterPlayerEvent(PLAYER_EVENT_ON_CHARACTER_CREATE, function(_, player)
    forgetCharacter(player:GetGUIDLow())
end)

RegisterPlayerEvent(PLAYER_EVENT_ON_CHARACTER_DELETE, function(_, guid)
    forgetCharacter(guid)
end)

RegisterPlayerEvent(PLAYER_EVENT_ON_LOGIN, function(_, player)
    initPlayer(player)
end)

RegisterPlayerEvent(PLAYER_EVENT_ON_LOGOUT, function(_, player)
    state[player:GetGUIDLow()] = nil
end)

RegisterPlayerEvent(PLAYER_EVENT_ON_COMPLETE_QUEST, function(_, player, quest)
    local st = getState(player)
    if st then sendQuestCheck(player, st, quest:GetId()) end
end)

-- Don't unlearn inside the learn hook (the core is mid-way through learnSpell, e.g.
-- handing out quest rewards); flag it and strip on the next tick instead.
RegisterPlayerEvent(PLAYER_EVENT_ON_LEARN_SPELL, function(_, player, spellId)
    local st = getState(player)
    if st and lockedSpells(player)[spellId] and not st.spells[spellId] then
        st.stripPending = true
    end
end)

RegisterPlayerEvent(PLAYER_EVENT_ON_LEVEL_CHANGE, function(_, player)
    checkLevels(player)
end)

-- Kills and area changes are noisy: once the bridge has synced the slot's locations,
-- only send ids that are actually locations. Before that, send everything (the
-- bridge drops unknown ids) so nothing found pre-sync is lost.
local function sendIfTracked(player, kind, gameId)
    local st = getState(player)
    if not st then return end
    if next(st.locations) == nil or st.locations[locId(kind, gameId)] then
        sendCheck(player, kind, gameId)
    end
end

RegisterPlayerEvent(PLAYER_EVENT_ON_UPDATE_ZONE, function(_, player, _, newArea)
    sendIfTracked(player, AP.LOC.EXPLORE, newArea)
    local st = getState(player)
    if st then enforceZone(player, st) end
end)

RegisterPlayerEvent(PLAYER_EVENT_ON_KILL_CREATURE, function(_, player, creature)
    sendIfTracked(player, AP.LOC.RARE, creature:GetEntry())
end)

-- `.ap` chat commands (debug).
RegisterPlayerEvent(PLAYER_EVENT_ON_COMMAND, function(_, player, command)
    if not player then return end -- console
    local cmd = command:lower()
    if cmd == "ap where" then
        say(player, string.format("zone %d, area %d, map %d, pos %.2f %.2f %.2f",
            player:GetZoneId(), player:GetAreaId(), player:GetMapId(),
            player:GetX(), player:GetY(), player:GetZ()))
        return false
    elseif cmd == "ap status" then
        local st = getState(player)
        say(player, "Status: " .. tostring(st and st.lastStatus or "no state"):gsub("\t", " | "))
        return false
    end
end)

---------------------------------------------------------------------------------------
-- class trainer checks
---------------------------------------------------------------------------------------
-- Class trainers sell one Archipelago check per pooled spell, at that spell's level and
-- price. The addon lists them in the trainer window (an "Archipelago" section) and sends
-- "BUY <spell>" when you train one; the server checks everything again here.

local TRAINER_RANGE = 15   -- yards: you must be at a class trainer to buy

local function atClassTrainer(player)
    local trainers = (ArchipelagoData and ArchipelagoData.trainers) or {}
    for _, creature in ipairs(player:GetCreaturesInRange(TRAINER_RANGE) or {}) do
        if trainers[creature:GetEntry()] == player:GetClass() then return true end
    end
    return false
end

local function buyTrainerCheck(player, st, spellId)
    for _, c in ipairs(trainerChecks(player)) do
        if c.spell == spellId then
            local id = locId(AP.LOC.TRAINER, c.spell)
            local loc = st.locations[id]
            if not loc then return end                       -- not a location in this slot
            if loc.checked or st.sent[id] then
                toAddon(player, "B", id)                     -- already bought: resync the addon
            elseif not atClassTrainer(player) then
                say(player, "Talk to a trainer of your class to buy that check.")
            elseif player:GetLevel() < c.level then
                say(player, string.format("The %s check needs level %d.", c.name, c.level))
            elseif player:GetCoinage() < c.cost then
                player:SendNotification("You don't have enough money.")
            else
                player:ModifyMoney(-c.cost)
                sendCheck(player, AP.LOC.TRAINER, c.spell)
                toAddon(player, "B", id)
                say(player, string.format("Bought the %s check: %s", c.name,
                    loc.contents ~= "" and loc.contents or "an unknown item"))
            end
            return
        end
    end
end

-- Messages from the addon (whispered to self).
RegisterServerEvent(SERVER_EVENT_ON_ADDON_MESSAGE, function(_, sender, _, prefix, msg)
    if prefix ~= AP.PREFIX or not sender then return end
    local st = getState(sender)
    if not st then return end
    if msg == "SYNC" then
        refreshFromDB(sender, st, false)
        fullSyncToAddon(sender, st)
    else
        local spell = msg:match("^BUY\t(%d+)$")
        if spell then buyTrainerCheck(sender, st, tonumber(spell)) end
    end
end)

